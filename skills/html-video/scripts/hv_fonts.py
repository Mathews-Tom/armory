"""Provision a user-selected, redistributable font into a project.

The package ships no font. ``add_font`` copies the user's selected file, requires
an explicit licence declaration and licence text, and records both in
``PROVENANCE.json``. It generates ``assets/fonts.css`` and compiler-visible
inline font faces in ``index.html``. Templates refer to the alias ``HV Text``.
"""

from __future__ import annotations

import hashlib
import re
import posixpath
from dataclasses import dataclass
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import quote

from hv_provenance import (
    FONT_FORMATS,
    Entry,
    FontMeta,
    font_metadata_error,
    read_provenance,
    safe_project_path,
    write_provenance,
)

FONTS_CSS = "assets/fonts.css"
FONTS_DIR = "assets/fonts"
LICENSES_DIR = "assets/fonts/licenses"
DEFAULT_ALIAS = "HV Text"

FONTS_CSS_HEADER = (
    "/* Generated by `html_video.py fonts add` from PROVENANCE.json.\n"
    "   No font is provisioned until a font has been added; the audit fails loudly meanwhile. */\n"
)

_LICENSE_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9.+:_-]*$")


class FontError(RuntimeError):
    """The font or its declaration cannot be accepted."""


def sniff_format(data: bytes) -> str:
    """Font container format from magic bytes: woff2, woff, ttf or otf."""
    head = data[:4]
    if head == b"wOF2":
        return "woff2"
    if head == b"wOFF":
        return "woff"
    if head == b"OTTO":
        return "otf"
    if head in (b"\x00\x01\x00\x00", b"true"):
        return "ttf"
    if head == b"ttcf":
        raise FontError(
            "font collections (.ttc/.otc) are not supported; extract one face first"
        )
    raise FontError(
        "file is not a woff2, woff, ttf or otf font (unrecognised magic bytes)"
    )


def render_fonts_css(entries: list[Entry], *, inline: bool = False) -> str:
    blocks: list[str] = []
    faces = [e for e in entries if e.font is not None]
    for entry in sorted(
        faces,
        key=lambda e: (e.font.alias, e.font.weight, e.font.style)
        if e.font
        else ("", "", ""),
    ):
        font = entry.font
        if font is None:
            continue
        problem = font_metadata_error(font)
        if problem:
            raise FontError(f"{entry.path}: {problem}")
        relative = entry.path if inline else posixpath.relpath(entry.path, "assets")
        name = quote(relative, safe="/-._~")
        blocks.append(
            "@font-face {\n"
            f'  font-family: "{font.alias}";\n'
            f'  src: url("./{name}") format("{FONT_FORMATS[font.format]}");\n'
            f"  font-weight: {font.weight};\n"
            f"  font-style: {font.style};\n"
            "  font-display: block;\n"
            "}\n"
        )
    return FONTS_CSS_HEADER + "".join(blocks)


@dataclass(frozen=True)
class FontRecord:
    alias: str
    weight: str
    style: str
    path: str
    license_file: str
    sha256: str


class _FontStyleParser(HTMLParser):
    def __init__(self, source: str) -> None:
        super().__init__(convert_charrefs=True)
        self.source = source
        self.lines = [
            0,
            *(index + 1 for index, char in enumerate(source) if char == "\n"),
        ]
        self.head_end: int | None = None
        self.style_start: int | None = None
        self.styles: list[tuple[int, int]] = []

    def _offset(self) -> int:
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "style" and dict(attrs).get("id") == "html-video-fonts":
            self.style_start = self._offset()

    def handle_endtag(self, tag: str) -> None:
        if tag == "head" and self.head_end is None:
            self.head_end = self._offset()
        if tag == "style" and self.style_start is not None:
            end = self.source.index(">", self._offset()) + 1
            self.styles.append((self.style_start, end))
            self.style_start = None


def _inline_fonts(source: str, css: str) -> str:
    parser = _FontStyleParser(source)
    parser.feed(source)
    parser.close()
    if parser.style_start is not None or len(parser.styles) > 1:
        raise FontError(
            "index.html must have at most one closed html-video-fonts style"
        )
    block = f'<style id="html-video-fonts">\n{css}</style>'
    if parser.styles:
        start, end = parser.styles[0]
        return source[:start] + block + source[end:]
    if parser.head_end is None:
        raise FontError("index.html needs a closed <head> for inline font declarations")
    return source[: parser.head_end] + block + "\n" + source[parser.head_end :]


def _slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower() or "font"


def add_font(
    project: Path,
    *,
    font_file: Path,
    family: str,
    license_id: str,
    license_file: Path,
    source: str,
    alias: str = DEFAULT_ALIAS,
    weight: str = "400",
    style: str = "normal",
    replace: bool = False,
) -> FontRecord:
    if not family.strip() or not source.strip():
        raise FontError(
            "--family (the font's real family name) and --source (where it was obtained) are required"
        )
    if not _LICENSE_ID.fullmatch(license_id):
        raise FontError(
            "--license-id must be an SPDX identifier or LicenseRef-… token without spaces"
        )
    if not project.is_dir():
        raise FontError(f"project directory {project} does not exist")
    for label, path in (("font file", font_file), ("licence file", license_file)):
        if not path.is_file() or path.stat().st_size == 0:
            raise FontError(f"{label} {path} is missing or empty")
    font_data, license_data = font_file.read_bytes(), license_file.read_bytes()
    fmt = sniff_format(font_data)
    font_meta = FontMeta(alias, weight, style, fmt, family.strip())
    problem = font_metadata_error(font_meta)
    if problem:
        raise FontError(problem)
    font_hash = hashlib.sha256(font_data).hexdigest()
    license_hash = hashlib.sha256(license_data).hexdigest()
    font_rel = f"{FONTS_DIR}/{_slug(font_file.stem)}-{font_hash[:8]}.{fmt}"
    license_rel = f"{LICENSES_DIR}/{license_hash[:8]}-{_slug(license_file.stem)}.txt"

    entries, problems = read_provenance(project)
    if problems:
        raise FontError("PROVENANCE.json must be fixed first: " + "; ".join(problems))
    clash = next(
        (
            e
            for e in entries
            if e.font
            and (e.font.alias, e.font.weight, e.font.style) == (alias, weight, style)
        ),
        None,
    )
    if clash is not None and clash.sha256 != font_hash and not replace:
        raise FontError(
            f"{alias!r} {weight} {style} is already provisioned from a different file; pass --replace to swap it"
        )
    if any(e.path == font_rel and e is not clash for e in entries):
        raise FontError(
            'this file is already provisioned for another face; use one weight range (e.g. "100 900") for a variable font'
        )
    kept = [e for e in entries if e is not clash]
    entry = Entry(
        path=font_rel,
        source=source.strip(),
        license=license_id,
        license_file=license_rel,
        sha256=font_hash,
        font=font_meta,
    )

    updated = [*kept, entry]
    try:
        font_target = safe_project_path(project, font_rel)
        license_target = safe_project_path(project, license_rel)
        css_target = safe_project_path(project, FONTS_CSS)
        html_target = safe_project_path(project, "index.html")
        safe_project_path(project, "PROVENANCE.json")
        old_target = safe_project_path(project, clash.path) if clash else None
    except ValueError as exc:
        raise FontError(str(exc)) from exc
    if not html_target.is_file():
        raise FontError("project index.html is missing")
    css = render_fonts_css(updated)
    try:
        html = _inline_fonts(
            html_target.read_text(encoding="utf-8"),
            render_fonts_css(updated, inline=True),
        )
    except (OSError, UnicodeError) as exc:
        raise FontError(f"cannot read project index.html: {exc}") from exc
    for target, data in ((font_target, font_data), (license_target, license_data)):
        if target.exists() and (not target.is_file() or target.read_bytes() != data):
            raise FontError(
                f"existing asset {target.relative_to(project)} has different bytes"
            )
    for target, data in ((font_target, font_data), (license_target, license_data)):
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.write_bytes(data)
    write_provenance(project, updated)
    css_target.parent.mkdir(parents=True, exist_ok=True)
    css_target.write_text(css, encoding="utf-8")
    html_target.write_text(html, encoding="utf-8")
    if (
        clash is not None
        and old_target is not None
        and clash.path != font_rel
        and not any(e.path == clash.path for e in updated)
    ):
        old_target.unlink(missing_ok=True)
    return FontRecord(alias, weight, style, font_rel, license_rel, font_hash)
