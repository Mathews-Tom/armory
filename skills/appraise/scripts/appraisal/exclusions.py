@dataclass
class Attributes:
    """Root .gitattributes linguist overrides (repository-declared)."""

    generated: list[str] = field(default_factory=list)
    vendored: list[str] = field(default_factory=list)
    documentation: list[str] = field(default_factory=list)

    @classmethod
    def parse(cls, text: str) -> Attributes:
        attrs = cls()
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            pattern, *flags = line.split()
            for flag in flags:
                if flag.startswith("-") or flag.endswith("=false"):
                    continue
                name = flag.split("=")[0]
                target = {
                    "linguist-generated": attrs.generated,
                    "linguist-vendored": attrs.vendored,
                    "linguist-documentation": attrs.documentation,
                }.get(name)
                if target is not None:
                    target.append(pattern)
        return attrs

    @staticmethod
    def matches(path: str, patterns: list[str]) -> bool:
        for pattern in patterns:
            pat = pattern.lstrip("/")
            if pat.endswith("/**"):
                if path.startswith(pat[:-3] + "/"):
                    return True
            elif fnmatch.fnmatch(path, pat) or fnmatch.fnmatch(
                PurePosixPath(path).name, pat
            ):
                return True
        return False


def language_of(path: str) -> str | None:
    return LANGUAGES.get(PurePosixPath(path).suffix.lower())


def classify(
    path: str, size: int, attrs: Attributes | None = None, head: bytes | None = None
) -> str:
    """Return the category for a path; `head` is the leading bytes of the blob when available."""
    lower = path.lower()
    pure = PurePosixPath(lower)
    parts = pure.parts
    dirs = set(parts[:-1])
    name, suffix = pure.name, pure.suffix

    if attrs is not None and attrs.matches(path, attrs.vendored):
        return "vendored"
    if attrs is not None and attrs.matches(path, attrs.generated):
        return "generated"
    if dirs & _VENDOR_DIRS:
        return "vendored"
    if dirs & _BUILD_DIRS and not lower.startswith(".github/"):
        return "build_output"
    if name in _LOCKFILES:
        return "lockfile"
    if suffix in _BINARY_EXT:
        return "binary"
    if name.endswith((".min.js", ".min.css", ".bundle.js", ".map")):
        return "minified"
    if _GENERATED_NAME.search(name):
        return "generated"
    if head is not None:
        if b"\0" in head[:4096]:
            return "binary"
        if _GENERATED_MARKER.search(head[:600]):
            return "generated"
    if dirs & _FIXTURE_DIRS:
        return "fixture"
    if (
        dirs & _BENCH_DIRS
        and suffix not in _DOC_EXT
        and (dirs & _RESULT_DIRS or suffix in _DATA_EXT or suffix == ".json")
    ):
        return "benchmark_result"
    if suffix in _DATA_EXT or suffix == ".ipynb":
        return "data"
    if suffix in {".json", ".xml", ".yaml", ".yml"} and size > 200_000:
        return "data"
    if any(lower.startswith(prefix) for prefix in _CI_PREFIXES):
        return "ci"
    if _is_test(parts, name):
        return "test"
    if attrs is not None and attrs.matches(path, attrs.documentation):
        return "docs"
    if suffix in _DOC_EXT or name in {
        "readme",
        "license",
        "changelog",
        "authors",
        "notice",
        "copying",
    }:
        return "docs"
    if name in _BUILD_FILES:
        return "build"
    if suffix in _SOURCE_EXT:
        return "source" if size <= 1_000_000 else "data"
    if suffix in _CONFIG_EXT or name.startswith(".") or name in _MANIFESTS:
        return "config"
    return "data" if size > 500_000 else "config"


def _is_test(parts: tuple[str, ...], name: str) -> bool:
    if any(p in _TEST_DIRS for p in parts[:-1]):
        return True
    return bool(
        name.startswith("test_")
        or re.search(r"(_test|\.test|\.spec|_spec)\.[a-z0-9]+$", name)
        or name in {"conftest.py", "test.py", "tests.py"}
    )


def is_manifest(path: str) -> bool:
    name = PurePosixPath(path.lower()).name
    return name in _LOCKFILES or name in _MANIFESTS or name.startswith("requirements")


def subsystem_of(path: str) -> str:
    """Stable component key: package-aware leading directories."""
    parts = PurePosixPath(path).parts
    if len(parts) == 1:
        return "(root)"
    head = parts[0]
    if (
        head
        in {
            "src",
            "lib",
            "pkg",
            "internal",
            "app",
            "packages",
            "crates",
            "cmd",
            "apps",
            "services",
            "modules",
        }
        and len(parts) > 2
    ):
        return "/".join(parts[:3]) if len(parts) > 3 else "/".join(parts[:2])
    if head in {"tests", "test", "docs", "scripts", "benchmarks"} and len(parts) > 2:
        return "/".join(parts[:2])
    return head
