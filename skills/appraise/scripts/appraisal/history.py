"""Single-pass commit history loading from the mirror."""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .gitio import Mirror
from .identity import email_key, is_ai_coauthor, parse_coauthors

_AI_BODY = re.compile(
    r"(generated with \[?(claude|codex|copilot|cursor|aider)|co-authored-by:\s*(claude|copilot|codex|gemini|cursor))",
    re.IGNORECASE,
)
_AI_MENTION = re.compile(
    r"\b(claude|copilot|codex|chatgpt|gpt-?[345]\w*|cursor ai|aider|gemini|devin|sub-?agents?|llm|ai-(generated|assisted)|generated by ai)\b",
    re.IGNORECASE,
)
_SEP = "\x1f"
_REC = "\x1e"


@dataclass
class Commit:
    sha: str
    parents: tuple[str, ...]
    author_name: str
    author_email: str
    author_key: str
    committer_email: str
    author_time: int
    commit_time: int
    subject: str
    coauthors: list[tuple[str, str]] = field(default_factory=list)
    ai_assisted: bool = False
    ai_mentioned: bool = False
    files: list[tuple[str, int, int]] = field(default_factory=list)

    @property
    def is_merge(self) -> bool:
        return len(self.parents) > 1

    @property
    def coauthor_keys(self) -> set[str]:
        return {email_key(e) for _, e in self.coauthors}

    def added(self, paths: set[str] | None = None) -> int:
        return sum(
            a for p, a, _ in self.files if a > 0 and (paths is None or p in paths)
        )


def load_history(mirror: Mirror, revision: str) -> dict[str, Commit]:
    """Load every commit reachable from revision; merges carry no numstat, so nothing is double counted."""
    fmt = _SEP.join(
        [
            "%H",
            "%P",
            "%an",
            "%ae",
            "%ce",
            "%at",
            "%ct",
            "%s",
            "%(trailers:key=Co-authored-by,valueonly,separator=%x1d)",
            "%b",
        ]
    )
    out = mirror.git(
        "log",
        "--no-renames",
        "--numstat",
        "--date-order",
        f"--format={_REC}{fmt}{_SEP}",
        revision,
        timeout=3600,
    )
    commits: dict[str, Commit] = {}
    for record in out.split(_REC):
        parts = record.split(_SEP)
        if len(parts) < 11:
            continue
        sha, parents, an, ae, ce, at, ct, subject, trailers, body, numstat = parts[:11]
        coauthors = parse_coauthors(trailers)
        commit = Commit(
            sha=sha.strip(),
            parents=tuple(parents.split()),
            author_name=an,
            author_email=ae.strip().lower(),
            author_key=email_key(ae),
            committer_email=ce.strip().lower(),
            author_time=int(at or 0),
            commit_time=int(ct or 0),
            subject=subject[:300],
            coauthors=[(n, e) for n, e in coauthors if not is_ai_coauthor(n, e)],
            ai_assisted=any(is_ai_coauthor(n, e) for n, e in coauthors)
            or bool(_AI_BODY.search(body)),
            ai_mentioned=bool(_AI_MENTION.search(subject) or _AI_MENTION.search(body)),
        )
        for line in numstat.strip().splitlines():
            cols = line.split("\t")
            if len(cols) == 3:
                commit.files.append(
                    (
                        cols[2],
                        int(cols[0]) if cols[0].isdigit() else -1,
                        int(cols[1]) if cols[1].isdigit() else -1,
                    )
                )
        commits[commit.sha] = commit
    return commits
