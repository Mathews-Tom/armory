from __future__ import annotations

import json
from typing import Any

import jsonschema
import pytest
from appraisal.exclusions import classify
from appraisal.sampling import python_central_modules
from appraisal.schema import (
    SCHEMA_DIR,
    SCHEMA_NAMES,
    _validate,
    errors_for,
    load_schema,
)


@pytest.mark.parametrize("name", SCHEMA_NAMES)
def test_bundled_schemas_are_valid_draft_2020_12(name: str) -> None:
    jsonschema.Draft202012Validator.check_schema(load_schema(name))


@pytest.mark.parametrize(
    "doc",
    [
        {"schema_version": "1.0"},
        {"schema_version": "2.0", "rubric_id": "Bad Id"},
        json.loads(
            (SCHEMA_DIR.parent / "rubrics" / "software_engineering.json").read_text()
        ),
    ],
)
def test_stdlib_validator_agrees_with_jsonschema(doc: dict[str, Any]) -> None:
    ours = errors_for(doc, "rubric")
    theirs = list(
        jsonschema.Draft202012Validator(load_schema("rubric")).iter_errors(doc)
    )
    assert bool(ours) == bool(theirs)


def test_unsupported_keywords_fail_loudly() -> None:
    schema = {"type": "string", "format": "email", "dependentRequired": {}}
    with pytest.raises(ValueError, match="unsupported schema keyword"):
        _validate("x", schema, schema, "$", [])


@pytest.mark.parametrize(
    ("path", "category"),
    [
        ("src/pkg/latest.py", "source"),
        ("tests/test_api.py", "test"),
        ("pkg/api_test.go", "test"),
        ("vendor/github.com/x/y.go", "vendored"),
        ("node_modules/a/index.js", "vendored"),
        ("dist/bundle.js", "build_output"),
        ("web/app.min.js", "minified"),
        ("proto/api_pb2.py", "generated"),
        ("uv.lock", "lockfile"),
        ("tests/fixtures/sample.py", "fixture"),
        ("benchmarks/results/run.json", "benchmark_result"),
        ("benchmarks/evidence/r30/REPORT.md", "docs"),
        ("benchmarks/evidence/task-1.json", "benchmark_result"),
        ("benchmarks/methodology.md", "docs"),
        ("data/train.csv", "data"),
        (".github/workflows/ci.yml", "ci"),
        ("docs/adr/001.md", "docs"),
        ("Makefile", "build"),
        ("assets/logo.png", "binary"),
    ],
)
def test_path_classification(path: str, category: str) -> None:
    assert classify(path, 100) == category


def test_generated_markers_need_generator_phrasing() -> None:
    assert (
        classify("src/a.py", 10, head=b"# Code generated by protoc. DO NOT EDIT.\n")
        == "generated"
    )
    assert (
        classify(
            "src/a.py",
            10,
            head=b'"""Summaries are NEVER auto-generated during a query."""\n',
        )
        == "source"
    )


def test_import_centrality_finds_the_most_depended_on_module() -> None:
    texts = {
        "src/pkg/core.py": "x = 1\n",
        "src/pkg/util.py": "import os\n",
        "src/pkg/a.py": "from pkg.core import x\n",
        "src/pkg/b.py": "from pkg import core\n",
        "src/pkg/c.py": "import pkg.core\nfrom pkg.util import y\n",
    }
    assert python_central_modules(texts) == {"src/pkg/core.py"}
